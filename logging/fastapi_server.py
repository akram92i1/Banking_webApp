@app.post("/api/chat")
async def chat_endpoint(request: ChatRequest, authorization: Optional[str] = Header(None)):
    """
    Main Entry Point.
    1. Calls OpenRouter to classify.
    2. Routes to appropriate internal function.
    """
    token = request.token
    if not token and authorization:
        if authorization.startswith("Bearer "):
            token = authorization.split(" ")[1]
        else:
            token = authorization

    # Extract User ID from Token (Security Best Practice)
    user_id = request.user_id
    if token:
        extracted_user = extract_user_from_token(token)
        if extracted_user and extracted_user != "unknown_user":
            user_id = extracted_user

    # ANSI Color for Blue
    BLUE = "\033[94m"
    YELLOW = "\033[93m"
    RESET = "\033[0m"
    print(f"\n[INFO] [FASTAPI] Incoming Chat from {BLUE}{user_id}{RESET}: '{request.message}'")
    logger.info(f"Incoming Chat: {request.message}")
            
    
    # 1. Build User Context
    user_context = UserContext(
        user_id=user_id,
        role=UserRole.USER, # Default to user
        location="unknown",
        preferences={},
        transaction_history=[],
        token=token
    )
    
    # 2. Call Local Brain (Intent Classification & SQL Gen)
    if not internal_agent:
        return {"response": "AI Service Unavailable"}

    print("   [FASTAPI] Loading Schema & Calling Local Brain...")
    schema = load_schema()
    
    # Pass message, schema, AND user_id to LOCAL agent
    brain_response = await internal_agent.process_user_intent(request.message, schema, user_id)
    
    response_type = brain_response.get("type", "CHAT")
    
    print(f"[DECISION] [BRAIN DECISION] Type: {response_type}")
    print(f"[DEBUG] Raw Brain Response: {brain_response}")

    # 3. Execution Routing
    if response_type == "QUERY":
        sql_query = brain_response.get("sql")
        print(f"   [INTERNAL] Executing SQL: {sql_query}")
        
        # New Direct DB Execution (Raw SQL)
        results, error = await execute_raw_sql(sql_query, app.state.pool)
        
        # --- AUTO-CORRECTION LOOP (Multi-Turn) ---
        retry_count = 0
        max_retries = 2
        
        while error and retry_count < max_retries:
            retry_count += 1
            print(f"⚠️ [AUTO-CORRECT] Attempt {retry_count}/{max_retries}. Failed: {error}")
            
            # Attempt correction
            fixed_sql = await internal_agent.fix_sql_query(sql_query, error, schema)
            
            if fixed_sql:
                print(f"🔄 [AUTO-CORRECT] Retrying with: {fixed_sql}")
                # Execute the NEW query
                results, new_error = await execute_raw_sql(fixed_sql, app.state.pool)
                
                if new_error:
                    # If failed again, update error and query for next loop iteration
                    error = new_error
                    sql_query = fixed_sql # IMPORTANT: Feed the NEW broken query to the next fix
                    print(f"❌ [AUTO-CORRECT] Auto-Fix Failed: {new_error}")
                else:
                    # Success!
                    error = None
                    print(f"✅ [AUTO-CORRECT] Success on retry {retry_count}!")
            else:
                 print("Cannot generate fix.")
                 break # Cannot fix, exit loop
        
        if error:
             return {"response": f"I tried to process your request but encountered an internal database error even after {retry_count} retries: {error}"}
        # ----------------------------

        # Print Result in Yellow
        if results:
            print(f"{YELLOW}   [DB RESULT] {json.dumps(results, indent=2, default=str)}{RESET}")
        else:
            print(f"{YELLOW}   [DB RESULT] No records found.{RESET}")

        # Serialize results for response
        # In a real app, we might pass this back to LLM to summarize. 
        # For now, return the raw data nicely formatted or just the list.
        
        # Simple text formatter
        if results:
            if internal_agent:
                 print(f"   [INTERNAL] Summarizing {len(results)} rows with Local LLM...")
                 response_text = await internal_agent.summarize_query_results(results, request.message)
            else:
                 # Fallback if agent not loaded
                 response_text = f"Here is the data I found:\n\nFound {len(results)} records.\n"
                 for i, row in enumerate(results[:5]):
                     response_text += f"- {row}\n"
                 if len(results) > 5:
                     response_text += f"...and {len(results)-5} more."
        else:
             response_text = "I searched the database but found no matching records."
             
        print(f"[SUCCESS] [INTERNAL] Data Result: {len(results)} rows.")
        return {"response": response_text}
              
    else: 
        # CHAT MODE - Return OpenRouter's answer directly
        chat_response = brain_response.get("response") or "I couldn't generate a response."
        if not isinstance(chat_response, str):
            chat_response = str(chat_response)
            
        print(f"[SUCCESS] [BRAIN] Chat Response: {chat_response[:100]}...")
        return {"response": chat_response}

    return {"response": "I'm having trouble connecting to the Banking Brain right now."}

