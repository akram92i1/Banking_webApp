# Modified to return (results, error_message)
async def execute_raw_sql(sql_query: str, pool) -> (List[Dict], str):
    """
    Executes valid SQL generated by the Local Agent.
    Returns: (results_list, error_message)
    """
    if not pool:
        return [], "No connection pool available."

    # 1. Validation
    cleaned_sql = sql_query.strip()
    if not cleaned_sql.lower().startswith("select"):
        return [], "Blocked non-SELECT query for security."
    
    if ";" in cleaned_sql.replace(";", ""): 
        pass 
        
    print(f"   [DB] Executing SQL: {cleaned_sql}")
    
    try:
        async with pool.acquire() as connection:
            rows = await connection.fetch(cleaned_sql)
            return [dict(row) for row in rows], None # Success, No Error
    except Exception as e:
        print(f"[ERROR] [DB] Query Failed: {e}")
        return [], str(e) # Failure, Return Error

